"""Build the resume from resume.json.

Writes:
  files/brandon-russell-resume.pdf   public PDF, no phone number (committed)
  Brandon_Russell_Resume.pdf         private PDF with phone number (gitignored)
  _cv-resume.md                      resume sections included by cv.qmd

The phone number is read from _resume/private.json ({"phone": "..."}), which is
gitignored. Without that file only the public outputs are built.

usage: python _resume/build.py
"""
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PUBLIC = ROOT / "files" / "brandon-russell-resume.pdf"
PRIVATE = ROOT / "Brandon_Russell_Resume.pdf"
PARTIAL = ROOT / "_cv-resume.md"


def find_quarto():
    exe = shutil.which("quarto")
    if exe:
        return exe
    local = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Quarto" / "bin" / "quarto.exe"
    if local.exists():
        return str(local)
    sys.exit("quarto not found")


def compile_pdf(out, phone=""):
    cmd = [find_quarto(), "typst", "compile", str(HERE / "resume.typ"), str(out)]
    if phone:
        cmd += ["--input", f"phone={phone}"]
    subprocess.run(cmd, check=True)


data = json.loads((HERE / "resume.json").read_text(encoding="utf-8"))

# ---- website partial ---------------------------------------------------------
# Same sections, order, and wording as the PDF.
def two_columns(cols):
    out = ["::: {.grid}"]
    for col in cols:
        out += ["::: {.g-col-12 .g-col-md-6}"] + [f"- {item}" for item in col] + [":::"]
    return out + [":::", ""]


md = ["<!-- Generated by _resume/build.py from _resume/resume.json. Do not edit by hand. -->", "",
      "## Summary", "", data["summary"], "",
      "## Certifications", ""] + two_columns(data["certifications"])
md += ["## Skills", ""] + two_columns(data["skills"])
md += ["## Education", ""]
for e in data["education"]:
    md += [f"**{e['degree']}** &nbsp;·&nbsp; {e['date']} \\", f"*{e['school']}*", ""]
md += ["## Publications", ""]
md += [f"- {p['text']}" + (f" <{p['url']}>" if "url" in p else "") for p in data["publications"]] + [""]
md += ["## Professional experience", ""]
for role in data["experience"]:
    md += [f"### {role['title']}", "",
           f"*{role['org']}, {role['location']}* &nbsp;·&nbsp; {role['dates']}", ""]
    md += [f"- {b}" for b in role["bullets"]] + [""]
PARTIAL.write_text("\n".join(md), encoding="utf-8", newline="\n")

# ---- PDFs --------------------------------------------------------------------
compile_pdf(PUBLIC)
private = HERE / "private.json"
phone = json.loads(private.read_text(encoding="utf-8"))["phone"] if private.exists() else ""
if phone:
    compile_pdf(PRIVATE, phone)

# ---- checks ------------------------------------------------------------------
try:
    import fitz
except ImportError:
    fitz = None
if fitz:
    pub = fitz.open(PUBLIC)
    text = " ".join(page.get_text() for page in pub)
    assert len(pub) == 2, f"public PDF has {len(pub)} pages, expected 2"
    assert not re.search(r"\d{3}[-.\s)]{1,2}\d{3}[-.\s]\d{4}", text), "phone-like number in the public PDF"
    if phone:
        digits = re.sub(r"\D", "", phone)
        assert digits not in re.sub(r"\D", "", text), "phone number found in the public PDF"
        assert digits not in PUBLIC.read_bytes().decode("latin-1"), "phone number bytes in the public PDF"
        priv = fitz.open(PRIVATE)
        assert len(priv) == 2 and phone in priv[0].get_text(), "private PDF is missing the phone number"
    print("public PDF:", PUBLIC.name, len(pub), "pages, no phone number")
print("private PDF:", "built" if phone else "skipped (no private.json)")
print("partial:", PARTIAL.name)
